"""Load Luke Barousse's 2023 `data_jobs` extract into the shared Neon Postgres DB.

The CSV is the ~786k-row Hugging Face dataset:
https://huggingface.co/datasets/lukebarousse/data_jobs

It is kept in dedicated, NORMALISED tables so it does not mix with the live
scraped snapshot in `jobs`:

    barousse_jobs        one row per unique posting (INT identity job_id)
    barousse_skills      skill dimension (skill name + type)
    barousse_job_skills  posting <-> skill bridge table
                         (job_id, skill_id with FKs, tidy/long form)
    barousse_skill_demand
                         view: postings and share of postings per skill

Idempotency: each CSV row gets a stable 64-bit fingerprint. Jobs are upserted
on that fingerprint and posting/skill links on (job_id, skill_id), so
re-running only adds or refreshes rows -- it never deletes. Exact duplicate
CSV rows are skipped and reported.

Loading is streaming and chunked: each chunk goes through a TEMP table + COPY
in its own transaction, so memory use stays flat even though the CSV is
~231 MB. job_id is INT rather than BIGINT purely to keep the link table's
index bloat inside the free Neon project's 512 MB cap (this dataset is
static, ~786k postings).

Usage:
    python scripts/load_barousse_jobs.py --dry-run
    python scripts/load_barousse_jobs.py --csv C:/path/to/data_jobs.csv
    python scripts/load_barousse_jobs.py --limit 5000          # smoke test
    python scripts/load_barousse_jobs.py --db-url "postgresql://..."
"""
import argparse
import ast
import csv
import hashlib
import json
import os
import sys
import time
from collections import Counter, defaultdict
from dataclasses import dataclass
from datetime import datetime, timezone
from decimal import Decimal, InvalidOperation
from pathlib import Path

import psycopg
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[1]
load_dotenv(ROOT / ".env")

# The CSV belongs beside the Quarto project's other data, one level above the
# pipeline. Keep the same convention as scripts/load_skills_demand.py.
DEFAULT_CSV = ROOT.parent / "data" / "data_jobs.csv"

CHUNK_ROWS = 100_000

EXPECTED_COLUMNS = [
    "job_title_short",
    "job_title",
    "job_location",
    "job_via",
    "job_schedule_type",
    "job_work_from_home",
    "search_location",
    "job_posted_date",
    "job_no_degree_mention",
    "job_health_insurance",
    "job_country",
    "salary_rate",
    "salary_year_avg",
    "salary_hour_avg",
    "company_name",
    "job_skills",
    "job_type_skills",
]

SCHEMA_TABLES = """
CREATE TABLE IF NOT EXISTS barousse_jobs (
    job_id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    row_fingerprint        BIGINT NOT NULL UNIQUE,
    job_title_short        TEXT,
    job_title              TEXT,
    job_location           TEXT,
    job_via                TEXT,
    job_schedule_type      TEXT,
    job_work_from_home     BOOLEAN,
    search_location        TEXT,
    job_posted_date        TIMESTAMPTZ,
    job_no_degree_mention  BOOLEAN,
    job_health_insurance   BOOLEAN,
    job_country            TEXT,
    salary_rate            TEXT,
    salary_year_avg        NUMERIC,
    salary_hour_avg        NUMERIC,
    company_name           TEXT,
    source_file            TEXT NOT NULL,
    loaded_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS barousse_skills (
    skill_id    SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill       TEXT NOT NULL UNIQUE,
    skill_type  TEXT,
    skill_types TEXT[] NOT NULL DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS barousse_job_skills (
    job_id   INT NOT NULL REFERENCES barousse_jobs(job_id) ON DELETE CASCADE,
    skill_id SMALLINT NOT NULL REFERENCES barousse_skills(skill_id) ON DELETE CASCADE,
    PRIMARY KEY (job_id, skill_id)
);
"""

SCHEMA_INDEXES = ""  # intentionally empty -- see note below

# Secondary indexes are intentionally NOT created, to stay under the free
# Neon project's 512 MB cap (measured sizes at full load; re-add if upgraded:
#   barousse_job_skills_skill_idx   ~20 MB (+ maintenance cost during load)
#   barousse_jobs_posted_date_idx   ~23 MB
#   barousse_jobs_company_idx       ~13 MB
#   barousse_jobs_country_idx       ~5 MB
#   barousse_jobs_title_short_idx   ~5 MB
# Point lookups by job_id / (job_id, skill_id) still use the primary keys.)

SCHEMA_VIEWS = """
CREATE OR REPLACE VIEW barousse_skill_demand AS
SELECT
    s.skill,
    s.skill_type,
    count(*) AS postings,
    round(
        100.0 * count(*) / NULLIF((SELECT count(*) FROM barousse_jobs), 0),
        2
    ) AS pct_of_postings
FROM barousse_job_skills js
JOIN barousse_skills s USING (skill_id)
GROUP BY s.skill_id, s.skill, s.skill_type;

CREATE OR REPLACE VIEW barousse_skill_demand_by_title AS
SELECT
    j.job_title_short,
    s.skill,
    s.skill_type,
    count(*) AS postings
FROM barousse_job_skills js
JOIN barousse_jobs j USING (job_id)
JOIN barousse_skills s USING (skill_id)
GROUP BY j.job_title_short, s.skill_id, s.skill, s.skill_type;
"""

STAGING_TABLE = """
CREATE TEMP TABLE staging_barousse_jobs (
    row_fingerprint       BIGINT NOT NULL,
    job_title_short       TEXT,
    job_title             TEXT,
    job_location          TEXT,
    job_via               TEXT,
    job_schedule_type     TEXT,
    job_work_from_home    BOOLEAN,
    search_location       TEXT,
    job_posted_date       TIMESTAMPTZ,
    job_no_degree_mention BOOLEAN,
    job_health_insurance  BOOLEAN,
    job_country           TEXT,
    salary_rate           TEXT,
    salary_year_avg       NUMERIC,
    salary_hour_avg       NUMERIC,
    company_name          TEXT,
    skills                JSONB NOT NULL DEFAULT '[]'::jsonb,
    source_file           TEXT NOT NULL
) ON COMMIT DROP
"""

COPY_SQL = """
COPY staging_barousse_jobs (
    row_fingerprint, job_title_short, job_title, job_location, job_via,
    job_schedule_type, job_work_from_home, search_location, job_posted_date,
    job_no_degree_mention, job_health_insurance, job_country, salary_rate,
    salary_year_avg, salary_hour_avg, company_name, skills, source_file
) FROM STDIN
"""

INSERT_JOBS_SQL = """
INSERT INTO barousse_jobs (
    row_fingerprint, job_title_short, job_title, job_location, job_via,
    job_schedule_type, job_work_from_home, search_location, job_posted_date,
    job_no_degree_mention, job_health_insurance, job_country, salary_rate,
    salary_year_avg, salary_hour_avg, company_name, source_file
)
SELECT
    row_fingerprint, job_title_short, job_title, job_location, job_via,
    job_schedule_type, job_work_from_home, search_location, job_posted_date,
    job_no_degree_mention, job_health_insurance, job_country, salary_rate,
    salary_year_avg, salary_hour_avg, company_name, source_file
FROM staging_barousse_jobs
ON CONFLICT (row_fingerprint) DO NOTHING
"""

INSERT_LINKS_SQL = """
INSERT INTO barousse_job_skills (job_id, skill_id)
SELECT DISTINCT j.job_id, s.skill_id
FROM staging_barousse_jobs st
JOIN barousse_jobs j ON j.row_fingerprint = st.row_fingerprint
CROSS JOIN LATERAL jsonb_array_elements_text(st.skills) AS skill_name(skill)
JOIN barousse_skills s ON s.skill = skill_name.skill
ON CONFLICT DO NOTHING
"""

INSERT_SKILLS_SQL = """
INSERT INTO barousse_skills (skill, skill_type, skill_types)
VALUES (%s, %s, %s)
ON CONFLICT (skill) DO UPDATE SET
    skill_type  = EXCLUDED.skill_type,
    skill_types = EXCLUDED.skill_types
"""


@dataclass
class Stats:
    rows: int = 0
    unique: int = 0
    duplicates: int = 0
    jobs_with_skills: int = 0
    skill_mentions: int = 0
    invalid_skill_cells: int = 0
    invalid_type_cells: int = 0
    invalid_dates: int = 0
    invalid_salaries: int = 0
    first_posted: datetime | None = None
    last_posted: datetime | None = None


def clean_text(value: str | None) -> str | None:
    text = (value or "").strip()
    return text or None


def normalise_skill(value) -> str:
    """Lower-case and collapse whitespace so joins to scraped tags are stable."""
    return " ".join(str(value).strip().lower().split())


def parse_bool(value: str | None) -> bool | None:
    text = (value or "").strip().lower()
    if text in {"true", "t", "1", "yes"}:
        return True
    if text in {"false", "f", "0", "no"}:
        return False
    return None


def parse_decimal(value: str | None) -> tuple[Decimal | None, bool]:
    text = (value or "").strip()
    if not text:
        return None, False
    try:
        return Decimal(text), False
    except InvalidOperation:
        return None, True


def parse_timestamp(value: str | None) -> tuple[datetime | None, bool]:
    text = (value or "").strip()
    if not text:
        return None, False
    try:
        parsed = datetime.fromisoformat(text)
    except ValueError:
        return None, True
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed, False


def parse_skill_list(raw: str | None) -> tuple[list[str], bool]:
    """Parse the CSV's Python-literal skill list, e.g. "['r', 'python']"."""
    text = (raw or "").strip()
    if not text:
        return [], False
    try:
        value = ast.literal_eval(text)
    except (ValueError, SyntaxError, TypeError):
        return [], True
    if not isinstance(value, (list, tuple)):
        return [], True

    skills: list[str] = []
    seen: set[str] = set()
    for item in value:
        skill = normalise_skill(item)
        if skill and skill not in seen:
            seen.add(skill)
            skills.append(skill)
    return skills, False


def parse_type_skills(raw: str | None) -> tuple[dict[str, list[str]], bool]:
    """Parse `job_type_skills`, e.g. "{'programming': ['python', 'sql']}"."""
    text = (raw or "").strip()
    if not text:
        return {}, False
    try:
        value = ast.literal_eval(text)
    except (ValueError, SyntaxError, TypeError):
        return {}, True
    if not isinstance(value, dict):
        return {}, True

    result: dict[str, list[str]] = {}
    for type_name, items in value.items():
        if not isinstance(items, (list, tuple)):
            continue
        key = normalise_skill(type_name)
        if not key:
            continue
        skills: list[str] = []
        seen: set[str] = set()
        for item in items:
            skill = normalise_skill(item)
            if skill and skill not in seen:
                seen.add(skill)
                skills.append(skill)
        if skills:
            result[key] = skills
    return result, False


def fingerprint(record: dict[str, str]) -> int:
    """Stable 64-bit fingerprint of one raw CSV row (all expected columns)."""
    payload = "\x1f".join(record.get(col, "") or "" for col in EXPECTED_COLUMNS)
    digest = hashlib.sha256(payload.encode("utf-8")).digest()
    return int.from_bytes(digest[:8], "big", signed=True)


def parse_record(record: dict[str, str]) -> dict:
    skills, bad_skills = parse_skill_list(record.get("job_skills"))
    type_skills, bad_types = parse_type_skills(record.get("job_type_skills"))
    posted, bad_posted = parse_timestamp(record.get("job_posted_date"))
    salary_year, bad_salary_year = parse_decimal(record.get("salary_year_avg"))
    salary_hour, bad_salary_hour = parse_decimal(record.get("salary_hour_avg"))

    return {
        "row_fingerprint": fingerprint(record),
        "job_title_short": clean_text(record.get("job_title_short")),
        "job_title": clean_text(record.get("job_title")),
        "job_location": clean_text(record.get("job_location")),
        "job_via": clean_text(record.get("job_via")),
        "job_schedule_type": clean_text(record.get("job_schedule_type")),
        "job_work_from_home": parse_bool(record.get("job_work_from_home")),
        "search_location": clean_text(record.get("search_location")),
        "job_posted_date": posted,
        "job_no_degree_mention": parse_bool(record.get("job_no_degree_mention")),
        "job_health_insurance": parse_bool(record.get("job_health_insurance")),
        "job_country": clean_text(record.get("job_country")),
        "salary_rate": clean_text(record.get("salary_rate")),
        "salary_year_avg": salary_year,
        "salary_hour_avg": salary_hour,
        "company_name": clean_text(record.get("company_name")),
        "skills": skills,
        "type_skills": type_skills,
        "invalid_skills": bad_skills,
        "invalid_types": bad_types,
        "invalid_date": bad_posted,
        "invalid_salary": bad_salary_year or bad_salary_hour,
    }


def iter_jobs(csv_path: Path, limit: int | None = None):
    """Yield parsed postings, streaming the CSV instead of loading it into RAM."""
    with csv_path.open(newline="", encoding="utf-8-sig") as fh:
        reader = csv.DictReader(fh)
        missing = [c for c in EXPECTED_COLUMNS if c not in (reader.fieldnames or [])]
        if missing:
            raise SystemExit(
                f"{csv_path}: missing expected column(s): {', '.join(missing)}\n"
                f"found: {', '.join(reader.fieldnames or ['<empty file>'])}"
            )

        for index, record in enumerate(reader, start=1):
            if limit is not None and index > limit:
                break
            yield parse_record(record)


def update_stats(
    job: dict,
    stats: Stats,
    skill_type_counts: dict[str, Counter],
    skill_counts: Counter,
) -> None:
    stats.unique += 1
    if job["invalid_skills"]:
        stats.invalid_skill_cells += 1
    if job["invalid_types"]:
        stats.invalid_type_cells += 1
    if job["invalid_date"]:
        stats.invalid_dates += 1
    if job["invalid_salary"]:
        stats.invalid_salaries += 1

    posted = job["job_posted_date"]
    if posted is not None:
        if stats.first_posted is None or posted < stats.first_posted:
            stats.first_posted = posted
        if stats.last_posted is None or posted > stats.last_posted:
            stats.last_posted = posted

    skills = job["skills"]
    if skills:
        stats.jobs_with_skills += 1
    stats.skill_mentions += len(skills)

    skill_set = set(skills)
    for skill in skills:
        skill_counts[skill] += 1
    for type_name, typed_skills in job["type_skills"].items():
        for skill in typed_skills:
            if skill in skill_set:
                skill_type_counts[skill][type_name] += 1


def print_stats(csv_path: Path, stats: Stats, skill_counts: Counter, elapsed: float) -> None:
    print(f"csv:         {csv_path}")
    print(f"rows read:   {stats.rows:,}")
    print(
        f"unique:      {stats.unique:,} postings "
        f"({stats.duplicates:,} exact duplicate rows skipped)"
    )
    print(f"with skills: {stats.jobs_with_skills:,} postings")
    print(f"links:       {stats.skill_mentions:,} posting-skill pairs")
    print(f"skills:      {len(skill_counts):,} distinct")
    if stats.first_posted and stats.last_posted:
        print(
            f"date range:  {stats.first_posted:%Y-%m-%d} .. "
            f"{stats.last_posted:%Y-%m-%d}"
        )
    if stats.invalid_skill_cells or stats.invalid_type_cells:
        print(
            f"bad cells:   {stats.invalid_skill_cells:,} job_skills, "
            f"{stats.invalid_type_cells:,} job_type_skills (left empty)"
        )
    if stats.invalid_dates or stats.invalid_salaries:
        print(
            f"bad values:  {stats.invalid_dates:,} dates, "
            f"{stats.invalid_salaries:,} salaries (left null)"
        )
    if stats.unique:
        print("\ntop skills:")
        for skill, count in skill_counts.most_common(15):
            pct = 100.0 * count / stats.unique
            print(f"  {skill:<22} {count:>9,}  ({pct:5.1f}% of postings)")
    print(f"\nelapsed:     {elapsed:.1f}s")


def dry_run(csv_path: Path, limit: int | None) -> None:
    stats = Stats()
    skill_type_counts: dict[str, Counter] = defaultdict(Counter)
    skill_counts: Counter = Counter()
    seen: set[int] = set()
    started = time.perf_counter()

    for job in iter_jobs(csv_path, limit):
        stats.rows += 1
        if job["row_fingerprint"] in seen:
            stats.duplicates += 1
            continue
        seen.add(job["row_fingerprint"])
        update_stats(job, stats, skill_type_counts, skill_counts)
        if stats.rows % 100_000 == 0:
            print(f"  ...read {stats.rows:,} rows", flush=True)

    print_stats(csv_path, stats, skill_counts, time.perf_counter() - started)
    print("\ndry run -- database not touched")


def table_count(conn, table: str) -> int:
    return conn.execute(f"SELECT count(*) FROM {table}").fetchone()[0]


def upsert_skills(
    conn,
    skill_counts: Counter,
    skill_type_counts: dict[str, Counter],
) -> None:
    rows = []
    for skill in sorted(skill_counts):
        counts = skill_type_counts.get(skill, Counter())
        # Most frequent type wins; ties break alphabetically so reruns are stable.
        types = sorted(counts, key=lambda name: (-counts[name], name))
        rows.append((skill, types[0] if types else None, types))
    if not rows:
        return
    with conn.cursor() as cur:
        cur.executemany(INSERT_SKILLS_SQL, rows)


def load(conn, csv_path: Path, limit: int | None) -> dict:
    """Stream the CSV in committed chunks; each chunk is idempotent on rerun."""
    started = time.perf_counter()
    stats = Stats()
    skill_type_counts: dict[str, Counter] = defaultdict(Counter)
    skill_counts: Counter = Counter()
    seen: set[int] = set()

    conn.execute(SCHEMA_TABLES)
    before_jobs = table_count(conn, "barousse_jobs")
    before_skills = table_count(conn, "barousse_skills")
    before_links = table_count(conn, "barousse_job_skills")
    conn.commit()

    def job_tuple(job: dict) -> tuple:
        return (
            job["row_fingerprint"],
            job["job_title_short"],
            job["job_title"],
            job["job_location"],
            job["job_via"],
            job["job_schedule_type"],
            job["job_work_from_home"],
            job["search_location"],
            job["job_posted_date"],
            job["job_no_degree_mention"],
            job["job_health_insurance"],
            job["job_country"],
            job["salary_rate"],
            job["salary_year_avg"],
            job["salary_hour_avg"],
            job["company_name"],
        )

    chunk_index = 0
    source = iter_jobs(csv_path, limit)
    source_done = False
    while not source_done:
        chunk = list()
        chunk_counts: Counter = Counter()
        chunk_type_counts: dict[str, Counter] = defaultdict(Counter)
        chunk_skills = list()
        for _ in range(CHUNK_ROWS):
            try:
                job = next(source)
            except StopIteration:
                source_done = True
                break
            stats.rows += 1
            if job["row_fingerprint"] in seen:
                stats.duplicates += 1
                continue
            seen.add(job["row_fingerprint"])
            update_stats(job, stats, chunk_type_counts, chunk_counts)
            chunk.append(job_tuple(job))
            chunk_skills.append(json.dumps(job["skills"]))

        if not chunk:
            break

        chunk_index += 1
        with conn.transaction():
            conn.execute(STAGING_TABLE)
            with conn.cursor().copy(COPY_SQL) as copy:
                for base_row, skills_json in zip(chunk, chunk_skills, strict=True):
                    copy.write_row(base_row + (skills_json, csv_path.name))
            conn.execute(INSERT_JOBS_SQL)
            # The dimension table needs the chunk's skill names before the
            # bridge INSERT can join names to skill_ids.
            upsert_skills(conn, chunk_counts, chunk_type_counts)
            conn.execute(INSERT_LINKS_SQL)
        # Fold the chunk's skill counts into the run-wide accumulators.
        skill_counts.update(chunk_counts)
        for skill, type_counts in chunk_type_counts.items():
            skill_type_counts[skill].update(type_counts)
        print(
            f"  ...committed chunk {chunk_index} "
            f"({stats.rows:,} rows read, {stats.unique:,} unique so far)"
        )

    print("final skill types, indexes and views ...", flush=True)
    with conn.transaction():
        # Re-upsert with run-wide counts so skill_type reflects the whole
        # dataset, not just whichever chunk last saw the skill.
        upsert_skills(conn, skill_counts, skill_type_counts)
        if SCHEMA_INDEXES:
            conn.execute(SCHEMA_INDEXES)
        conn.execute(SCHEMA_VIEWS)

    return {
        "csv_path": csv_path,
        "stats": stats,
        "skill_counts": skill_counts,
        "elapsed": time.perf_counter() - started,
        "chunks": chunk_index,
        "before_jobs": before_jobs,
        "after_jobs": table_count(conn, "barousse_jobs"),
        "before_skills": before_skills,
        "after_skills": table_count(conn, "barousse_skills"),
        "before_links": before_links,
        "after_links": table_count(conn, "barousse_job_skills"),
    }


def print_load_summary(result: dict) -> None:
    print()
    print_stats(
        result["csv_path"],
        result["stats"],
        result["skill_counts"],
        result["elapsed"],
    )
    print(
        f"\nchunks committed:     {result['chunks']}"
    )
    print(
        f"barousse_jobs:        {result['before_jobs']:,} -> "
        f"{result['after_jobs']:,} (net new: {result['after_jobs'] - result['before_jobs']:,})"
    )
    print(
        f"barousse_skills:      {result['before_skills']:,} -> "
        f"{result['after_skills']:,} (net new: {result['after_skills'] - result['before_skills']:,})"
    )
    print(
        f"barousse_job_skills:  {result['before_links']:,} -> "
        f"{result['after_links']:,} (net new: {result['after_links'] - result['before_links']:,})"
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--csv",
        type=Path,
        default=DEFAULT_CSV,
        help=f"source CSV (default: {DEFAULT_CSV})",
    )
    parser.add_argument(
        "--db-url",
        help="Postgres DSN (default: $DATABASE_URL_UNPOOLED)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="validate and summarise the CSV without touching the database",
    )
    parser.add_argument(
        "--limit",
        type=int,
        help="only read the first N CSV rows (for smoke tests)",
    )
    args = parser.parse_args()

    if args.limit is not None and args.limit <= 0:
        parser.error("--limit must be positive")

    csv_path = args.csv.expanduser()
    if not csv_path.exists():
        hint = ""
        downloads = Path.home() / "Downloads" / "data_jobs.csv"
        if csv_path == DEFAULT_CSV and downloads.exists():
            hint = f"\nhint: found {downloads}; pass --csv \"{downloads}\""
        raise SystemExit(f"CSV not found: {csv_path}{hint}")

    if args.dry_run:
        dry_run(csv_path, args.limit)
        return

    dsn = args.db_url or os.environ.get("DATABASE_URL_UNPOOLED")
    if not dsn:
        print(
            "DATABASE_URL_UNPOOLED not set in environment/.env "
            "(or pass --db-url)",
            file=sys.stderr,
        )
        sys.exit(1)

    with psycopg.connect(dsn) as conn:
        result = load(conn, csv_path, args.limit)

    print_load_summary(result)


if __name__ == "__main__":
    main()
